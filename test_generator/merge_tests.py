def gen_synthesis_tests(tests):
    """Generate synthesis test as a list of dict configs (used in a loop).
    Each test runs: build sd, call gen, check (ticker_or_name) + any(numbers) + topics>=3
    """
    lines = []
    for t in tests:
        cfg = {
            "ticker": t["ticker"],
            "company": t["company_name"],
            "metrics": t["metrics"],
            "news": t["news"],
            "insider_trades": t["insider_trades"],
            "expected_numbers": t["expected_numbers"],
            "expected_topics": t["expected_topics"],
        }
        lines.append("        " + repr(cfg) + ",")
    return "\n".join(lines)


